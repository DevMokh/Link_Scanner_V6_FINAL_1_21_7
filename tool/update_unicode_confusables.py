#!/usr/bin/env python3
"""Generate Dart ASCII-target confusables from the official Unicode UTS #39 file.

By default downloads the pinned Unicode release. To make offline/reproducible
updates, pass --input path/to/confusables.txt. Only single-code-point sources
whose full target mapping is printable ASCII are emitted; this is the subset
used by Link Scanner's ASCII brand/domain skeleton comparison.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Dict

DEFAULT_VERSION = "18.0.0"
MAX_SOURCE_BYTES = 5 * 1024 * 1024


def parse_confusables(text: str, expected_version: str) -> Dict[int, str]:
    version_match = re.search(r"^#\s*Version:\s*([^\s]+)", text, re.MULTILINE)
    if not version_match or version_match.group(1) != expected_version:
        actual = version_match.group(1) if version_match else "missing"
        raise ValueError(
            f"Unicode data version mismatch: expected {expected_version}, got {actual}"
        )

    mappings: Dict[int, str] = {}
    for line_number, raw_line in enumerate(text.splitlines(), 1):
        line = raw_line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [part.strip() for part in line.split(";")]
        if len(fields) < 2:
            raise ValueError(f"Malformed Unicode mapping at line {line_number}")
        source_tokens = fields[0].split()
        target_tokens = fields[1].split()
        if len(source_tokens) != 1 or not target_tokens:
            # UTS #39 confusables are normally scalar-source mappings. Ignore
            # unsupported source sequences instead of generating partial data.
            continue
        try:
            source = int(source_tokens[0], 16)
            target_points = [int(token, 16) for token in target_tokens]
            target = "".join(chr(point) for point in target_points)
        except (ValueError, OverflowError) as exc:
            raise ValueError(f"Invalid code point at line {line_number}") from exc
        if source > 0x10FFFF or 0xD800 <= source <= 0xDFFF:
            raise ValueError(f"Invalid source scalar at line {line_number}")
        if any(point > 0x10FFFF or 0xD800 <= point <= 0xDFFF for point in target_points):
            raise ValueError(f"Invalid target scalar at line {line_number}")
        if not target or any(ord(char) < 0x21 or ord(char) > 0x7E for char in target):
            continue
        mappings[source] = target
    if not mappings:
        raise ValueError("No printable-ASCII confusable mappings were found")
    return mappings


def render_dart(mappings: Dict[int, str], version: str) -> str:
    lines = [
        "// Generated by tool/update_unicode_confusables.py. Do not edit manually.",
        "// Source: Unicode UTS #39 confusables.txt; printable-ASCII targets only.",
        "// SPDX-License-Identifier: Unicode-3.0",
        "// Unicode License V3 — COPYRIGHT AND PERMISSION NOTICE:",
        "// Copyright © 1991-2026 Unicode, Inc.",
        '// Permission is hereby granted, free of charge, to any person obtaining a copy of data files and any associated documentation (the "Data Files") or software and any associated documentation (the "Software") to deal in the Data Files or Software without restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute, and/or sell copies of the Data Files or Software, and to permit persons to whom the Data Files or Software are furnished to do so, provided that either (a) this copyright and permission notice appear with all copies of the Data Files or Software, or (b) this copyright and permission notice appear in associated Documentation.',
        "// THE DATA FILES AND SOFTWARE ARE PROVIDED AS IS, WITHOUT WARRANTY OF ANY KIND.",
        "// License: https://www.unicode.org/license.txt",
        "// Full notice: THIRD_PARTY_NOTICES.md (also included with this bundled data).",
        f"// Unicode data version: {version}.",
        f"const String kUnicodeConfusablesVersion = {json.dumps(version)};",
        f"const int kUnicodeConfusablesCount = {len(mappings)};",
        "const Map<int, String> kUnicodeConfusables = <int, String>{",
    ]
    for source, target in sorted(mappings.items()):
        dart_value = json.dumps(target, ensure_ascii=True).replace("$", r"\$")
        lines.append(f"  0x{source:04X}: {dart_value},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def download_source(version: str) -> str:
    url = f"https://www.unicode.org/Public/{version}/security/confusables.txt"
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "LinkScanner-Unicode-Data-Builder/1.0"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        content_type = response.headers.get("Content-Type", "")
        data = response.read(MAX_SOURCE_BYTES + 1)
    if len(data) > MAX_SOURCE_BYTES:
        raise ValueError("Unicode source file exceeds the 5 MiB safety limit")
    if "text" not in content_type.lower() and b"# confusables.txt" not in data[:256]:
        raise ValueError("Unicode server did not return the expected text data file")
    return data.decode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default=DEFAULT_VERSION)
    parser.add_argument("--input", type=Path, help="Use a previously downloaded file")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("lib/core/unicode_confusables_data.dart"),
    )
    parser.add_argument(
        "--minimum-mappings",
        type=int,
        default=1,
        help="Refuse to replace the bundled table unless at least this many mappings were parsed",
    )
    args = parser.parse_args()
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", args.version):
        parser.error("--version must use a numeric Unicode version such as 18.0.0")

    if args.minimum_mappings < 1:
        parser.error("--minimum-mappings must be at least 1")

    try:
        text = args.input.read_text(encoding="utf-8") if args.input else download_source(args.version)
        mappings = parse_confusables(text, args.version)
        if len(mappings) < args.minimum_mappings:
            raise ValueError(
                f"Only {len(mappings)} mappings parsed; minimum required is {args.minimum_mappings}"
            )
        generated = render_dart(mappings, args.version)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(generated, encoding="utf-8", newline="\n")
    except (OSError, UnicodeError, ValueError, TimeoutError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"Generated {len(mappings)} Unicode mappings into {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
